-- The database used by Week 23: the weather data from Weeks 19-22, plus
-- one week of sales from a (made-up) chain of weather-gear shops with one
-- store in each of the seven cities that have observations.
--
-- Sales were generated from the weather, so the two can be analysed
-- together: umbrellas sell on rainy days, wool socks when nights are cold,
-- sunglasses when it's sunny. On Sunday 2026-09-27 umbrellas were on a
-- 20% promotion, so that day's umbrella revenue is below units x list price.

CREATE TABLE cities (
    id          INTEGER PRIMARY KEY,
    name        TEXT    NOT NULL UNIQUE,
    country     TEXT    NOT NULL,
    population  INTEGER NOT NULL
);

CREATE TABLE observations (
    id                INTEGER PRIMARY KEY,
    city_id           INTEGER NOT NULL REFERENCES cities (id),
    observed_on       TEXT    NOT NULL,  -- ISO-8601 date: 'YYYY-MM-DD'
    temp_max_c        REAL    NOT NULL,  -- daily high, degrees Celsius
    temp_min_c        REAL    NOT NULL,  -- daily low, degrees Celsius
    precipitation_mm  REAL    NOT NULL,  -- rain or snow (as water), millimetres
    wind_ms           REAL,              -- mean wind speed, metres per second; NULL = sensor failure
    conditions        TEXT    NOT NULL   -- 'sun', 'cloud', 'rain' or 'snow'
);

