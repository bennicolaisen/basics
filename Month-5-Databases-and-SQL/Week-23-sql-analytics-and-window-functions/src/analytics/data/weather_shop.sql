CREATE TABLE products (
    id              INTEGER PRIMARY KEY,
    name            TEXT    NOT NULL UNIQUE,
    category        TEXT    NOT NULL,  -- the weather it sells in: 'rain', 'cold' or 'sun'
    list_price_sek  REAL    NOT NULL   -- Swedish kronor, before any promotion
);

CREATE TABLE stores (
    id         INTEGER PRIMARY KEY,
    city_id    INTEGER NOT NULL UNIQUE REFERENCES cities (id),
    opened_on  TEXT    NOT NULL
);

-- One row per store, product and day with at least one unit sold.
-- A product that sold nothing that day has no row (not a row with 0).
CREATE TABLE daily_sales (
    store_id     INTEGER NOT NULL REFERENCES stores (id),
    product_id   INTEGER NOT NULL REFERENCES products (id),
    sold_on      TEXT    NOT NULL,
    units        INTEGER NOT NULL CHECK (units > 0),
    revenue_sek  REAL    NOT NULL,  -- what was actually charged, promotions included
    PRIMARY KEY (store_id, product_id, sold_on)
);

